/**
 * Multi-diagram transcript corpus for wayfinder ticket #59 (map #38).
 *
 * A separate file on purpose. #59 acceptance 4 requires every existing harness
 * number to reproduce on the single-diagram subset, and that is only checkable
 * if the 244 original entries are byte-identical. They are: nothing here edits
 * `transcripts.ts` except the seventeen entries a full re-read found were
 * already multi-diagram, and the two new type fields.
 *
 * ## What makes an entry belong here
 *
 * One mermaid document cannot serve the request. That is a narrower test than
 * "the transcript describes several things":
 *
 *   - A list, a chain and a decision are all flowchart constructs. They belong
 *     in ONE document and do not qualify.
 *   - Two different diagram types qualify, because a mermaid document is
 *     exactly one type.
 *   - Two unconnected graphs of the SAME type qualify when drawing them as one
 *     document says something false. Two independent state machines in one
 *     `stateDiagram-v2` need the `--` region separator, which #56 measured
 *     failing to parse on `cov-state-grouped-regions`.
 *
 * ## `multiFrom`
 *
 * Not every entry here wants two diagrams at every effort level.
 *
 *   low     one diagram drops something the person explicitly asked for
 *   medium  one diagram is defensible but loses a distinction worth keeping
 *   high    two diagrams are better teaching, and one is correct when the
 *           point is to be fast
 *
 * An analogy is the clearest case. Drawing the valet key beside the OAuth
 * sequence is better at High and wrong at Low, where one diagram fast is the
 * whole point. Without this field a correct Low answer scores as a miss.
 *
 * ## Built from combinations, not invented situations
 *
 * Each entry is two scenarios already in `transcripts.ts`, joined the way a
 * real speaker joins them. `residual-list-retro` plus `swe-ci-pipeline` is a
 * retro board and the release process that caused it, and that is a meeting
 * that happens. The seams carry the connectives dictation actually produces:
 * `and then separately`, `ok next thing`, `while we are here`.
 *
 * Distribution is kept close to `transcripts.ts` so the additions do not skew
 * the corpus further toward dictation than the 196/33/32 it already sits at.
 *
 * DELIBERATELY NOT hand-tuned to pass. Several of these ask for a pair a
 * single-diagram pipeline cannot produce at all, which is the point.
 */
